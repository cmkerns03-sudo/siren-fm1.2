"""ABYSS's data for the firmware -> build/gen/abyss_data.h: the sounds of each world and layer (tools/abyss/curation.json,
by engine and preset name: abyss.c finds them at power-on), each one's calibration in its layer (tools/abyss/levels.json,
tests/abyss/level_cal.c: the trim that brings it to its layer's loudness, the tone that softens hard highs), the drum
kits (SIREN's, tools/siren/kits.json).
  tools/gen_abyss.py OUT.h"""
import json, sys
from pathlib import Path
T = Path(__file__).parent
W = ['CINEMATIC', 'COSMIC', 'DARK']
LAY = ['DRUMS', 'DRONE', 'PAD', 'LOW', 'MELO', 'BELL', 'SWELL', 'SUB']
cur = json.loads((T / 'abyss' / 'curation.json').read_text())
kits = json.loads((T / 'siren' / 'kits.json').read_text())
lev = json.loads((T / 'abyss' / 'levels.json').read_text()) if (T / 'abyss' / 'levels.json').exists() else {}
byname = {k['name']: k for s in kits.values() for k in s}
snd, idx, lst, trims, tones, spans = [], {}, [], [], [], []
for w in W:
    row = []
    for L in LAY:
        ks = cur[w].get(L, []) if L not in ('DRUMS', 'SUB') else []
        row.append((len(lst), len(ks)))
        for k in ks:
            e, p = k.split(':', 1)
            if e == 'FM6': sys.exit(f'gen_abyss: {k}: FM6 waits for the main loop (no)')
            if (e, p) not in idx: idx[(e, p)] = len(snd); snd.append((e, p))
            lst.append(idx[(e, p)])
            c = lev.get(f'{w}|{L}|{e}:{p}', {}); trims.append(int(c.get('trim', 0))); tones.append(int(c.get('tone', 0)))
    spans.append(row)
o = ['/* generated by tools/gen_abyss.py: ABYSS\'s sounds and drum kits */', '#pragma once',
     'typedef struct { const char *eng, *pre; } sd_snd_t;', 'typedef struct { uint16_t first; uint8_t n; } sd_span_t;',
     'typedef struct { char name[9]; uint8_t crush; uint16_t kick_n16[2]; uint8_t s[16][22]; } sd_kit_t;',
     f'#define SD_NSND {len(snd)}',
     'static const sd_snd_t SD_SND[SD_NSND] = {' + ', '.join(f'{{"{e}", "{p}"}}' for e, p in snd) + '};',
     f'#define SD_NLIST {len(lst)}',
     'static const uint8_t SD_LIST[SD_NLIST] = {' + ', '.join(map(str, lst)) + '};',
     'static const int8_t SD_TRIM[SD_NLIST] = {' + ', '.join(map(str, trims)) + '}, SD_TONE[SD_NLIST] = {' + ', '.join(map(str, tones)) + '};',
     f'#define SD_HAS_LEVELS {1 if lev else 0}',
     'static const sd_span_t SD_CUR[3][8] = {' + ', '.join('{' + ', '.join(f'{{{a}, {n}}}' for a, n in r) + '}' for r in spans) + '};']
kl, first = [], []
for w in W:
    first.append(len(kl)); kl += [byname[n] for n in cur[w]['KITS']]
o.append(f'#define SD_NKITS {len(kl)}')
o.append('static const uint8_t SD_KIT_FIRST[3] = {' + ', '.join(map(str, first)) + '}, SD_KIT_N[3] = {' + ', '.join(str(len(cur[w]['KITS'])) for w in W) + '};')
o.append('static const sd_kit_t SD_KITS[SD_NKITS] = {')
for k in kl:
    lanes = ', '.join('{' + ', '.join(str(x) for x in v) + '}' for v in k['lanes'])
    o.append(f'    {{"{k["name"]}", {k["crush"]}, {{{k["kickN16"]}, {k["kick2N16"]}}}, {{{lanes}}}}},')
o.append('};')
o.append('static const uint32_t SD_NOTE_INC[128] = {' + ', '.join(str(int(round(440 * 2 ** ((n - 69) / 12) / 44100 * 2 ** 32))) for n in range(128)) + '};')
Path(sys.argv[1]).write_text('\n'.join(o) + '\n')
print(f'abyss: {len(snd)} sounds, {len(kl)} drum kits -> {sys.argv[1]}')
