"""SIREN's data for the firmware -> build/gen/siren_data.h:
  the selection of sounds per style and layer (tools/siren/curation.json, the prototype's workshop export: the FM-1's
  own sounds (Clipper's, SIREN's WOB and, since 0.9.1, the community's OberVave voice: eng_obv.c), and WAVE only on the bass: the
  firmware keeps one wavetable in RAM), by engine and preset name (siren.c finds them at power-on);
  the drum kits (tools/siren/kits.json, tools/siren_kits.py on the prototype): 16 sounds each, the drum synth's bytes.

  tools/gen_siren.py OUT.h"""
import json, sys
from pathlib import Path
D = Path(__file__).with_name('siren')
STY = ['TECHNO', 'TRANCE', 'PSY', 'ACID', 'RAVE', 'HARD', 'DNB', 'HOUSE']
LAY = ['DRUMS', 'BASS', 'ARP', 'HOOK', 'PAD', 'STAB', 'FX']
cur = json.loads((D / 'curation.json').read_text()); kits = json.loads((D / 'kits.json').read_text())
# (0.5) each sound's calibration in its layer (tests/siren/level_cal.c -> tools/siren/levels.json): the trim (P_LEVEL
# steps, 2 a dB) that brings it to its layer's loudness, the tone (the track filter's low-pass, 0 open) that softens its
# hard highs. "LAYER|ENGINE:PRESET"
lev = json.loads((D / 'levels.json').read_text()) if (D / 'levels.json').exists() else {}
trims, tones = [], []
# (0.2) the engines a set can afford on the FM-1, six parts at once: no GRAIN, VPS, MACRO, VECTOR, STRINGS, TERRAIN, PHYS,
# SAMPLE, FM6 (its patch waits for the main loop's fm6_poll, Clipper's screen) or WAVE (one table in RAM)
LIGHT = {'ANALOG', 'ACID', 'TRIO', 'DIGITAL', 'PHASE', 'LOFI', 'NOISE', 'WHEEL', 'HYBRID', 'JUNO', 'WSEQ', 'FMX', 'VOICE', 'WOB',
         'OBERVAVE'}   # (0.9.1) the community's OberVave voice (eng_obv.c)
def fm1(k, L):
    if '/' in k and not k.startswith('siren/'): return False
    eng = (k.split('/', 1)[1] if '/' in k else k).split(':', 1)[0]
    return eng != 'WAVE' or L == 'BASS'
snd, idx = [], {}
o = ['/* generated by tools/gen_siren.py: SIREN\'s sounds and drum kits */', '#pragma once',
     'typedef struct { const char *eng, *pre; } sd_snd_t;', 'typedef struct { uint16_t first; uint8_t n; } sd_span_t;',
     'typedef struct { char name[9]; uint8_t crush; uint16_t kick_n16[2]; uint8_t s[16][22]; } sd_kit_t;']
spans, lst = [], []
for s in STY:
    row = []
    for L in LAY:
        ks = [k for k in cur[s].get(L, []) if fm1(k, L)] if L != 'DRUMS' else []
        row.append((len(lst), len(ks)))
        for k in ks:
            body = k.split('/', 1)[1] if '/' in k else k
            e, p = body.split(':', 1)
            if e not in LIGHT: sys.exit(f'gen_siren: {k} ({s} {L}): {e} is not one of the engines SIREN can afford')
            if (e, p) not in idx: idx[(e, p)] = len(snd); snd.append((e, p))
            lst.append(idx[(e, p)])
            if lev and f'{L}|{e}:{p}' not in lev: sys.exit(f'gen_siren: {L}|{e}:{p} has no calibration: run tests/siren/level_cal > tools/siren/levels.json')
            c = lev.get(f'{L}|{e}:{p}', {}); trims.append(int(c.get('trim', 0))); tones.append(int(c.get('tone', 0)))
    spans.append(row)
# (0.10) every layer's universe (each style's sounds, once) in 64: SIREN's banks are 64-bit masks (siren.c srb_*)
for L in LAY[1:6]:
    u = {k for st in STY for k in cur[st].get(L, []) if fm1(k, L)}
    if len(u) > 64: sys.exit(f'gen_siren: {L} has {len(u)} sounds over all the styles: 64 at most (siren.c SRB_MAX)')
o.append(f'#define SD_NSND {len(snd)}')
o.append('static const sd_snd_t SD_SND[SD_NSND] = {' + ', '.join(f'{{"{e}", "{p}"}}' for e, p in snd) + '};')
o.append(f'#define SD_NLIST {len(lst)}')
o.append('static const uint8_t SD_LIST[SD_NLIST] = {' + ', '.join(map(str, lst)) + '};')
o.append('#define SD_HAS_TRIM 1')
o.append('static const int8_t SD_TRIM[SD_NLIST] = {' + ', '.join(map(str, trims)) + '}, SD_TONE[SD_NLIST] = {' + ', '.join(map(str, tones)) + '};')
o.append('static const sd_span_t SD_CUR[8][7] = {' + ', '.join('{' + ', '.join(f'{{{a}, {n}}}' for a, n in r) + '}' for r in spans) + '};')
kl, first = [], []
for s in STY:
    first.append(len(kl)); kl += kits[s]
o.append(f'#define SD_NKITS {len(kl)}')
o.append('static const uint8_t SD_KIT_FIRST[8] = {' + ', '.join(map(str, first)) + '}, SD_KIT_N[8] = {' + ', '.join(str(len(kits[s])) for s in STY) + '};')
o.append('static const uint16_t SD_KICK_N16[SD_NKITS][2] = {' + ', '.join(f'{{{k["kickN16"]}, {k["kick2N16"]}}}' for k in kl) + '};')
o.append('static const sd_kit_t SD_KITS[SD_NKITS] = {')
for k in kl:
    lanes = ', '.join('{' + ', '.join(str(x) for x in v) + '}' for v in k['lanes'])
    o.append(f'    {{"{k["name"]}", {k["crush"]}, {{{k["kickN16"]}, {k["kick2N16"]}}}, {{{lanes}}}}},')
o.append('};')
o.append('static const uint32_t SD_NOTE_INC[128] = {' + ', '.join(str(int(round(440 * 2 ** ((n - 69) / 12) / 44100 * 2 ** 32))) for n in range(128)) + '};   /* a note\'s phase increment a sample (Q32) */')
Path(sys.argv[1]).write_text('\n'.join(o) + '\n')
print(f'siren: {len(snd)} sounds, {len(kl)} drum kits -> {sys.argv[1]}')
